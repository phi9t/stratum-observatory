/** Deterministic browser copy of the importable Python source of truth. */
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
const root=new URL('../examples/deepseek_v41/',import.meta.url);
const output=new URL('../src/pytorch-source.mjs',import.meta.url);
export function syncPythonSources(check=false){
 const files=fs.readdirSync(root).filter(name=>name.endsWith('.py')&&!['__init__.py','validate.py'].includes(name)).sort();
 const sources=Object.fromEntries(files.map(name=>[name,fs.readFileSync(new URL(name,root),'utf8')]));
 const content='/** Generated by tools/sync-pytorch.mjs. Edit examples/deepseek_v41/*.py. */\nexport const PYTHON_SOURCES='+JSON.stringify(sources)+';\n';
 const current=fs.existsSync(output)?fs.readFileSync(output,'utf8'):'';
 if(check&&current!==content)throw new Error('Python browser sources are stale; run npm run build.');
 if(!check&&current!==content)fs.writeFileSync(output,content);
}
if(process.argv[1]===fileURLToPath(import.meta.url))syncPythonSources(process.argv.includes('--check'));
